import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import path from 'node:path'

async function login(page:any){await page.goto('/');await page.getByLabel('管理员账号').fill('admin');await page.getByLabel('密码',{exact:true}).fill('browser-test-password');await page.getByRole('button',{name:'登录工作空间'}).click();await expect(page.getByRole('heading',{name:'最近扫描'})).toBeVisible()}

test('PDF editor, manual batch, rename, batch delete and permanent purge',async({page},testInfo)=>{
 await login(page)
 const buffer=await readFile(path.resolve('e2e/scan.png'))
 const first=`pdf-${testInfo.project.name}-one.png`,second=`pdf-${testInfo.project.name}-two.png`
 await page.locator('input[type=file]').setInputFiles([{name:first,mimeType:'image/png',buffer},{name:second,mimeType:'image/png',buffer}])
 await expect(page.getByRole('status')).toContainText('已接收 2 个文件')
 await page.getByLabel('本页全选').check()
 await page.getByRole('button',{name:'合并 PDF',exact:true}).click()
 const editor=page.getByRole('dialog')
 await expect(editor).toBeVisible()
 await page.getByRole('button',{name:'上移第 2 页',exact:true}).click()
 await page.getByRole('button',{name:'右旋第 1 页',exact:true}).click()
 await page.getByLabel('PDF 文件名').fill('pages-'+testInfo.project.name+'.pdf')
 await page.getByLabel('统一为 A4').check()
 await page.screenshot({path:testInfo.outputPath('pdf-editor.png'),fullPage:true})
 const downloadPromise=page.waitForEvent('download')
 await page.getByRole('button',{name:'生成并下载 PDF'}).click()
 const download=await downloadPromise
 expect(download.suggestedFilename()).toBe('pages-'+testInfo.project.name+'.pdf')
 await download.saveAs(testInfo.outputPath('merged.pdf'))
 await expect(editor).not.toBeVisible()
 page.once('dialog',dialog=>dialog.accept('e2e-batch-'+testInfo.project.name))
 await page.getByRole('button',{name:'拆分 / 归类'}).click()
 await expect(page.getByRole('status')).toContainText('已将选中文件移动到新批次')
 await page.getByRole('button',{name:'扫描批次',exact:true}).click()
 const row=page.locator('.batch-list article').filter({hasText:'e2e-batch-'+testInfo.project.name})
 await expect(row).toContainText('手动整理')
 page.once('dialog',dialog=>dialog.accept('renamed-'+testInfo.project.name))
 await row.getByRole('button',{name:'重命名批次'}).click()
 const renamed=page.locator('.batch-list article').filter({hasText:'renamed-'+testInfo.project.name})
 await expect(renamed).toBeVisible()
 await page.screenshot({path:testInfo.outputPath('batches.png'),fullPage:true})
 page.once('dialog',dialog=>dialog.accept())
 await renamed.getByRole('button',{name:'删除整个批次'}).click()
 await expect(renamed).toHaveCount(0)
 await page.getByRole('button',{name:'回收站',exact:true}).click()
 await page.getByLabel('选择 '+first,{exact:true}).check()
 await page.getByLabel('选择 '+second,{exact:true}).check()
 page.once('dialog',dialog=>dialog.accept())
 await page.getByRole('button',{name:'永久删除',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('已永久删除 2 个文件')
 await expect(page.getByLabel('选择 '+first,{exact:true})).toHaveCount(0)
})

test('system settings persist safe defaults and show real upload logs',async({page},testInfo)=>{
 await login(page)
 await page.getByRole('button',{name:'系统设置',exact:true}).click()
 await expect(page.getByRole('heading',{name:'系统设置'})).toBeVisible()
 await expect(page.getByLabel('原件保留天数')).toHaveValue('0')
 await expect(page.getByLabel('回收站保留天数')).toHaveValue('0')
 await page.getByLabel('推断批次间隔（秒）').fill('45')
 await page.getByRole('button',{name:'保存系统设置'}).click()
 await expect(page.getByRole('status')).toContainText('系统设置已保存')
 await expect(page.locator('.upload-log-list article').first()).toBeVisible()
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.screenshot({path:testInfo.outputPath('settings.png'),fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await page.reload()
 await page.getByRole('button',{name:'系统设置',exact:true}).click()
 await expect(page.getByLabel('推断批次间隔（秒）')).toHaveValue('45')
})

import { test, expect } from '@playwright/test'
import path from 'node:path'

test('upload, select, batch rotate, preview, restore and mobile layout',async({page},testInfo)=>{
 const errors:string[]=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await page.getByLabel('管理员账号').fill('admin')
 await page.getByLabel('密码',{exact:true}).fill('browser-test-password')
 await page.getByRole('button',{name:'登录工作空间'}).click()
 await expect(page.getByRole('heading',{name:'最近扫描'})).toBeVisible()
 const fixture=path.resolve('e2e/scan.png')
 const initialTrash=(await (await page.request.get('/api/files?deleted=true')).json()).total
 const buffer=await (await import('node:fs/promises')).readFile(fixture)
 const firstName=testInfo.project.name+'-first.png',secondName=testInfo.project.name+'-second.png'
 await page.locator('input[type=file]').setInputFiles([{name:firstName,mimeType:'image/png',buffer},{name:secondName,mimeType:'image/png',buffer}])
 await expect(page.getByRole('status')).toContainText('已接收 2 个文件')
 await page.getByLabel('本页全选').check()
 await page.getByRole('button',{name:'右旋 90°',exact:true}).click()
 await expect(page.locator('.rotation-badge')).toHaveCount(2)
 await expect(page.locator('.rotation-badge').first()).toHaveText('90°')
 await page.getByRole('button',{name:'左旋 90°',exact:true}).click()
 await expect(page.locator('.rotation-badge')).toHaveCount(0)
 await page.locator('.file-name').first().click()
 await expect(page.getByRole('dialog')).toBeVisible()
 await expect(page.locator('.preview-content img')).toBeVisible()
 await page.getByRole('button',{name:'右旋',exact:true}).click()
 await expect(page.locator('.preview-dialog header small')).toContainText('90°')
 const imageResponse=await page.request.get(await page.getByRole('link',{name:'下载方向修正 PNG'}).getAttribute('href') as string)
 expect(imageResponse.status()).toBe(200)
 expect(imageResponse.headers()['content-type']).toContain('image/png')
 await page.getByRole('button',{name:'关闭预览'}).click()
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.screenshot({path:testInfo.outputPath('inbox.png'),fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 page.once('dialog',dialog=>dialog.accept())
 await page.getByRole('button',{name:'移入回收站',exact:true}).click()
 await page.getByRole('button',{name:'回收站',exact:true}).click()
 await expect(page.locator('.file')).toHaveCount(initialTrash+2)
 await page.getByLabel('选择 '+firstName,{exact:true}).check()
 await page.getByLabel('选择 '+secondName,{exact:true}).check()
 await page.getByRole('button',{name:'恢复',exact:true}).click()
 await expect(page.locator('.file')).toHaveCount(initialTrash)
 await page.getByRole('button',{name:'收件箱',exact:true}).click()
 await expect(page.locator('.file')).toHaveCount(2)
 // Clean up only this project's synthetic rows before the next viewport test.
 await page.getByLabel('本页全选').check()
 page.once('dialog',dialog=>dialog.accept())
 await page.getByRole('button',{name:'移入回收站',exact:true}).click()
 await page.getByRole('button',{name:'退出登录'}).click()
 await expect(page.getByRole('button',{name:'登录工作空间'})).toBeVisible()
 expect(errors).toEqual([])
})

test('SSE keeps selection and preview while scanner uploads; dark theme',async({page,playwright},testInfo)=>{
 await page.emulateMedia({colorScheme:'dark'})
 await page.goto('/')
 await page.getByLabel('管理员账号').fill('admin')
 await page.getByLabel('密码',{exact:true}).fill('browser-test-password')
 await page.getByRole('button',{name:'登录工作空间'}).click()
 await expect(page.getByRole('heading',{name:'最近扫描'})).toBeVisible()
 const scanner=await playwright.request.newContext({baseURL:'http://127.0.0.1:18767',extraHTTPHeaders:{'X-Upload-Token':'isolated-browser-test-upload-token'}})
 const buffer=await (await import('node:fs/promises')).readFile(path.resolve('e2e/scan.png'))
 async function scan(name:string){const response=await scanner.post('/api/upload',{multipart:{paper:{name,mimeType:'image/png',buffer},device:'Synthetic scanner'}});expect(response.status()).toBe(200)}
 await scan('sse-first.png')
 await expect(page.locator('.file')).toHaveCount(1,{timeout:10000})
 await page.getByLabel('选择 sse-first.png',{exact:true}).check()
 await page.locator('.file-name').first().click()
 await scan('sse-second.png')
 await expect(page.locator('.file')).toHaveCount(2,{timeout:10000})
 await expect(page.getByRole('dialog')).toBeVisible()
 await expect(page.locator('.selection-count')).toHaveText('已选 1 个文件')
 await page.getByRole('button',{name:'关闭预览'}).click()
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.screenshot({path:testInfo.outputPath('dark-inbox.png'),fullPage:true})
 await page.getByLabel('本页全选').check()
 page.once('dialog',d=>d.accept())
 await page.getByRole('button',{name:'移入回收站',exact:true}).click()
 await scanner.dispose()
})

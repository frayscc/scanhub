import { test,expect } from '@playwright/test'
import { uploadFiles } from './ftp'
const tokens:string[]=[]
async function open(page:any){const created=page.waitForResponse((r:any)=>r.url().endsWith('/api/workspaces')&&r.request().method()==='POST');await page.goto('/');const data=await(await created).json();tokens.push(data.token);await expect(page.getByRole('heading',{name:/^本次扫描/,level:1})).toBeVisible();return data.token}
test.afterEach(async({request})=>{for(const token of tokens.splice(0))await request.post('/api/workspaces/end',{headers:{'X-Workspace-Token':token},data:{}})})
test('anonymous FTP workspace rotates, exports and ends without history',async({page},info)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 const token=await open(page)
 await expect(page.getByRole('button',{name:'登录工作空间'})).toHaveCount(0)
 await page.getByRole('button',{name:'开始扫描',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('已领取扫描仪')
 await uploadFiles(['one-'+info.project.name+'.png','two-'+info.project.name+'.png'])
 await expect(page.locator('.file')).toHaveCount(2,{timeout:10000})
 await page.getByLabel('本页全选').check()
 await page.getByRole('button',{name:'右旋 90°',exact:true}).click()
 await expect(page.locator('.rotation-badge').first()).toHaveText('90°')
 await page.getByRole('button',{name:'左旋 90°',exact:true}).click()
 await expect(page.locator('.rotation-badge')).toHaveCount(0)
 await page.getByRole('button',{name:'合并 PDF',exact:true}).click()
 await expect(page.getByRole('dialog')).toBeVisible()
 await page.getByRole('button',{name:'上移第 2 页'}).click()
 await page.getByRole('button',{name:'右旋第 1 页'}).click()
 await page.getByLabel('统一为 A4').check()
 const downloaded=page.waitForEvent('download')
 await page.getByRole('button',{name:'生成并下载 PDF'}).click()
 await(await downloaded).saveAs(info.outputPath('merged.pdf'))
 await expect(page.getByRole('dialog')).not.toBeVisible()
 await page.locator('.file-name').first().click()
 await expect(page.locator('.preview-content img')).toBeVisible()
 const original=page.waitForEvent('download');await page.getByRole('button',{name:'下载原件',exact:true}).click();await original
 await page.getByRole('button',{name:'关闭预览'}).click()
 await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:info.outputPath('workspace.png'),fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'结束并清理'}).click()
 await expect(page.getByRole('heading',{name:'本次工作台已结束'})).toBeVisible()
 expect((await page.request.get('/api/files',{headers:{'X-Workspace-Token':token}})).status()).toBe(401)
 expect(errors).toEqual([])
})
test('separate pages cannot see files or take an occupied scanner',async({page,context})=>{
 await open(page);await page.getByRole('button',{name:'开始扫描',exact:true}).click()
 await uploadFiles(['private.png']);await expect(page.locator('.file')).toHaveCount(1,{timeout:10000})
 const second=await context.newPage();await open(second)
 await expect(second.locator('.file')).toHaveCount(0)
 await second.getByRole('button',{name:'开始扫描',exact:true}).click()
 await expect(second.getByRole('alert')).toContainText('其他人')
 page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'结束并清理'}).click()
 await second.getByRole('button',{name:'开始扫描',exact:true}).click()
 await uploadFiles(['next-person.png']);await expect(second.locator('.file')).toHaveCount(1,{timeout:10000})
 await expect(second.locator('.file-name')).toHaveText('next-person.png')
 await expect(page.locator('.file')).toHaveCount(0)
 await second.close()
})
test('leaving a page revokes access and a new page has no history',async({page,request})=>{
 const token=await open(page);await page.getByRole('button',{name:'开始扫描',exact:true}).click()
 await uploadFiles(['leaving.png']);await expect(page.locator('.file')).toHaveCount(1,{timeout:10000})
 await page.goto('about:blank')
 await expect.poll(async()=>(await request.get('/api/files',{headers:{'X-Workspace-Token':token}})).status()).toBe(401)
 await open(page);await expect(page.locator('.file')).toHaveCount(0)
 await page.getByRole('button',{name:'开始扫描',exact:true}).click();await expect(page.getByRole('status')).toContainText('已领取扫描仪')
})
